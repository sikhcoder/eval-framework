"""Export a task as an Inspect AI task file.

Interop is a deliberate strategy, not a convenience. Labs already run Inspect, `verifiers`,
and METR-standard harnesses; an environment they can drop into an existing pipeline is
worth more than one that requires adopting our runner. The core stays thin precisely so
this stays cheap.
"""

from __future__ import annotations

from ef.core.types import TaskInstance

TEMPLATE = '''"""Auto-generated by eval-framework. Do not edit by hand."""

from inspect_ai import Task, task
from inspect_ai.dataset import Sample
from inspect_ai.scorer import Score, Target, accuracy, scorer
from inspect_ai.solver import basic_agent, system_message
from inspect_ai.util import sandbox

INSTRUCTION = {instruction!r}
INSTANCE_ID = {instance_id!r}


@scorer(metrics=[accuracy()])
def ef_verifier():
    """Delegates to the eval-framework verifier so scoring stays identical across harnesses."""

    async def score(state, target: Target) -> Score:
        from ef.core.registry import REGISTRY
        from ef.export.bridge import trace_from_inspect

        _, verifier = REGISTRY.resolve({task_id!r})
        generator, _ = REGISTRY.resolve({task_id!r})
        instance = generator.generate({seed!r})
        reward = verifier.verify(instance, await trace_from_inspect(state, sandbox()))
        return Score(
            value=reward.score,
            answer=reward.evidence[0] if reward.evidence else "",
            explanation="\\n".join(reward.evidence),
            metadata={{"dimensions": reward.dimensions, "tier": int(reward.tier)}},
        )

    return score


@task
def {func_name}():
    return Task(
        dataset=[Sample(input=INSTRUCTION, id=INSTANCE_ID)],
        solver=[system_message("You are operating in an isolated evaluation sandbox."),
                basic_agent()],
        scorer=ef_verifier(),
        sandbox="docker",
    )
'''


def export_inspect(instance: TaskInstance) -> str:
    """Render a runnable Inspect AI task module for one instance."""
    func_name = instance.spec.id.replace("/", "_").replace("-", "_")
    return TEMPLATE.format(
        instruction=instance.spec.instruction,
        instance_id=instance.instance_id,
        task_id=instance.spec.id,
        seed=instance.seed,
        func_name=func_name,
    )
